#!/usr/bin/env python3
"""Build the IPv4 -> country table for the dashboard map.

Input : DB-IP Lite country CSV (dbip-country-lite-YYYY-MM.csv, optionally .gz).
Output: src/geo_table.h - one byte per /14 block (16384 entries), 255 = unknown.

The table is a direct index: cc = GEO_TABLE[ip >> 18]. No search, no RAM.
A block keeps its majority country only when that country holds >= MIN_SHARE of
the block's addresses; otherwise it is 255 ("estimated, unknown") and the map
leaves it neutral instead of painting a wrong country.

Data: IP Geolocation by DB-IP <https://db-ip.com> - CC BY 4.0.
Regenerate monthly: stale data paints stale countries.

  python3 tools/build_geo_table.py dbip-country-lite.csv
  python3 tools/build_geo_table.py --fixture   # tiny self-check, no input file
"""
import argparse
import gzip
import ipaddress
import os
import sys

BITS = 14
SHIFT = 32 - BITS
N = 1 << BITS  # 16384
UNKNOWN = 255
MIN_SHARE = 0.60
DEFAULT_OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "geo_table.h")


def open_text(path):
    return gzip.open(path, "rt") if path.endswith(".gz") else open(path, encoding="utf-8")


def parse_rows(path):
    """Yield (first_ip, last_ip, cc) from the DB-IP CSV (IPv4 rows only)."""
    with open_text(path) as f:
        for line in f:
            if ":" in line:
                continue
            parts = line.strip().split(",")
            if len(parts) < 3:
                continue
            first, last, cc = parts[0], parts[1], parts[2].strip().upper()
            if len(cc) != 2 or not cc.isalpha() or cc == "ZZ":
                cc = ""  # reserved / unknown -> neutral
            try:
                a = int(ipaddress.IPv4Address(first))
                b = int(ipaddress.IPv4Address(last))
            except ValueError:
                continue
            if a <= b:
                yield a, b, cc


def build_table(rows, min_share=MIN_SHARE):
    """rows -> (bytes[N], sorted country codes). Pure function, used by the test."""
    blocks = [None] * N
    for a, b, cc in rows:
        if cc == "ZZ":
            cc = ""  # reserved / unknown -> neutral
        base = a >> SHIFT
        end = b >> SHIFT
        for blk in range(base, end + 1):
            lo = max(a, blk << SHIFT)
            hi = min(b, (blk << SHIFT) + (1 << SHIFT) - 1)
            votes = blocks[blk]
            if votes is None:
                votes = blocks[blk] = {}
            votes[cc] = votes.get(cc, 0) + (hi - lo + 1)

    codes = sorted({c for votes in blocks if votes for c in votes if c})
    if len(codes) > UNKNOWN:
        raise SystemExit("too many country codes for one byte")
    idx = {c: i for i, c in enumerate(codes)}

    out = bytearray([UNKNOWN]) * N
    for blk in range(N):
        votes = blocks[blk]
        if not votes:
            continue
        total = sum(votes.values())
        top, top_n = max(votes.items(), key=lambda kv: kv[1])
        if total and top and top_n / total >= min_share:
            out[blk] = idx[top]
    return bytes(out), codes


def self_check(rows, table, codes):
    """Known-IP smoke check; prints instead of asserting (the DB changes monthly)."""
    def cc_of(ip):
        b = table[int(ipaddress.IPv4Address(ip)) >> SHIFT]
        return "??(neutral)" if b == UNKNOWN else codes[b]

    for ip in ("8.8.8.8", "1.1.1.1", "200.160.2.3", "10.0.0.1"):
        print("  %-15s -> %s" % (ip, cc_of(ip)))

    known = sum(1 for b in table if b != UNKNOWN)
    print("  blocks mapped: %d/%d (%.1f%%), neutral %.1f%%" % (known, N, 100 * known / N, 100 * (N - known) / N))
    return known


def render_header(table, codes, source):
    lines = []
    lines.append("// Generated by tools/build_geo_table.py - do not edit by hand.")
    lines.append("// IP Geolocation by DB-IP <https://db-ip.com> - CC BY 4.0.")
    lines.append("// Source: %s. Regenerate monthly; stale data paints stale countries." % source)
    lines.append("// One byte per /14 IPv4 block: cc = GEO_TABLE[ip >> 18]; 255 = mixed/unknown.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#define GEO_TABLE_N %d" % len(table))
    lines.append("#define GEO_NCODES %d" % len(codes))
    lines.append("")
    lines.append("static const uint8_t GEO_TABLE[GEO_TABLE_N] PROGMEM = {")
    for i in range(0, len(table), 24):
        chunk = table[i:i + 24]
        lines.append("  " + ",".join(str(b) for b in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("// 2 chars per code, index = table byte. Single string: no pointer table on flash.")
    joined = "".join(codes)
    lines.append("static const char GEO_CODES[] PROGMEM =")
    for i in range(0, len(joined), 48):
        lines.append('  "%s"' % joined[i:i + 48])
    lines.append("  ;")
    lines.append("")
    return "\n".join(lines)


def fixture_rows():
    """One /14 with a single country, one 70/30, one 55/45, one reserved, one unmapped."""
    blk = 1 << SHIFT
    base = 0x0A000000  # arbitrary fixture
    rows = []
    # unanimous DE over the whole block
    rows.append((base, base + blk - 1, "DE"))
    # 70/30 FR/US: FR keeps the block at the 60% threshold
    b2 = base + blk
    cut = b2 + int(blk * 0.70) - 1
    rows.append((b2, cut, "FR"))
    rows.append((cut + 1, b2 + blk - 1, "US"))
    # 55/45 JP/CN: below threshold -> neutral
    b3 = b2 + blk
    cut3 = b3 + int(blk * 0.55) - 1
    rows.append((b3, cut3, "JP"))
    rows.append((cut3 + 1, b3 + blk - 1, "CN"))
    # reserved -> neutral
    b4 = b3 + blk
    rows.append((b4, b4 + blk - 1, "ZZ"))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", nargs="?", help="DB-IP Lite country CSV (.csv or .csv.gz)")
    ap.add_argument("-o", "--out", default=DEFAULT_OUT)
    ap.add_argument("--min-share", type=float, default=MIN_SHARE)
    ap.add_argument("--fixture", action="store_true", help="run the built-in fixture and exit")
    args = ap.parse_args()

    if args.fixture:
        table, codes = build_table(fixture_rows(), args.min_share)
        assert len(table) == N
        assert table[0x0A000000 >> SHIFT] != UNKNOWN                 # DE
        assert table[0x0A000000 >> SHIFT] == codes.index("DE")
        assert table[(0x0A000000 + (1 << SHIFT)) >> SHIFT] != UNKNOWN  # FR 70%
        assert table[(0x0A000000 + (2 << SHIFT)) >> SHIFT] == UNKNOWN  # JP 55%
        assert table[(0x0A000000 + (3 << SHIFT)) >> SHIFT] == UNKNOWN  # ZZ
        assert codes == ["CN", "DE", "FR", "JP", "US"]
        print("fixture ok: %d codes, %d bytes" % (len(codes), len(table)))
        return

    if not args.csv:
        ap.error("missing CSV (or use --fixture)")

    rows = list(parse_rows(args.csv))
    if not rows:
        raise SystemExit("no IPv4 rows parsed from %s" % args.csv)
    table, codes = build_table(rows, args.min_share)
    source = os.path.basename(args.csv)
    header = render_header(table, codes, source)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(header)

    print("wrote %s: %d bytes table, %d countries" % (args.out, len(table), len(codes)))
    self_check(rows, table, codes)


if __name__ == "__main__":
    main()
