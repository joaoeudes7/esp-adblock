// Lazy, idle-only batching: don't touch the socket while any query is in flight.
static bool dnsIdle() {
  for (int i = 0; i < INFLIGHT_N; i++)
    if (inflight[i].used) return false;
  return true;
}
static uint32_t lastSyslogSeq = 0, lastFlush = 0;
static void flushSyslogLazy(bool idle) {
  if (!syslogReady || !syslogHost.length()) return;
  uint32_t pending = evSeq - lastSyslogSeq;
  if (pending == 0) return;
  if (idle && dnsIdle()) {
    uint32_t now = millis();
    if (now - lastFlush < 500) return; // idle: at most every 0.5s
    lastFlush = now;
  } else if (pending < (uint32_t)(EV_N - 2)) {
    return; // busy: wait, unless the ring is about to overwrite
  }
  // At most 16 events per datagram; anything beyond that is flushed on the next round
  // (lastSyslogSeq tracks the LAST SENT, so pending events are never skipped).
  uint32_t oldest = (evSeq > EV_N) ? (evSeq - EV_N + 1) : 1;
  uint32_t from = lastSyslogSeq + 1;
  if (from < oldest) from = oldest;
  String m;
  int cnt = 0;
  for (uint32_t s = from; s <= evSeq && cnt < 16; s++) {
    BlockEv& e = evRing[s % EV_N];
    if (e.seq != s) continue;
    m += "<134>1 ESP-ADBlock - - - blocked=" + String(e.host) + " client=" + IPAddress(e.cip).toString() + "\n";
    lastSyslogSeq = s;
    cnt++;
  }
  if (cnt) {
    syslogCli.beginPacket(syslogHost.c_str(), syslogPort);
    syslogCli.write((const uint8_t*)m.c_str(), m.length());
    syslogCli.endPacket();
  }
}

// ---------- upstream selection (/dns.cfg: one IPv4 per line) ----------
// Every round probes each candidate with a tiny DNS query on its own socket (probeCli),
// so forwarding RTT (rttMs) stays pure. The pick only becomes the forwarder when no
// query is in flight: pollUpstream() matches replies against upstreamIP.
static void dnsReset() {
  dnsCount = 0;
  dnsCur = 0;
  dnsNext = -1;
  for (int i = 0; i < MAX_DNS; i++) {
    dnsRtt[i] = 0;
    dnsFails[i] = 0;
  }
}
static bool dnsAdd(String s) {
  s.trim();
  IPAddress ip;
  if (!s.length() || !ip.fromString(s) || (uint32_t)ip == 0) return false;
  for (int i = 0; i < dnsCount; i++)
    if (dnsList[i] == ip) return true; // dedupe
  if (dnsCount >= MAX_DNS) return false;
  dnsList[dnsCount++] = ip;
  return true;
}
// Accepts commas, spaces, semicolons or newlines as separators (dashboard textarea).
// Parses into a scratch list first: a bad request must not wipe the running list.
static bool dnsParseList(String csv) {
  IPAddress tmp[MAX_DNS];
  int n = 0;
  for (unsigned int i = 0; i < csv.length(); i++) {
    char ch = csv[i];
    if (ch == ';' || ch == '\n' || ch == '\r' || ch == ' ' || ch == '\t') csv.setCharAt(i, ',');
  }
  int start = 0;
  while (start < (int)csv.length() && n < MAX_DNS) {
    int sep = csv.indexOf(',', start);
    if (sep < 0) sep = csv.length();
    String one = csv.substring(start, sep);
    one.trim();
    IPAddress ip;
    if (one.length() && ip.fromString(one) && (uint32_t)ip != 0) {
      bool dup = false;
      for (int i = 0; i < n; i++)
        if (tmp[i] == ip) {
          dup = true;
          break;
        }
      if (!dup) tmp[n++] = ip;
    }
    start = sep + 1;
  }
  if (!n) return false;
  dnsReset();
  for (int i = 0; i < n; i++) dnsList[i] = tmp[i];
  dnsCount = n;
  return true;
}
static void loadDnsCfg() {
  dnsReset();
  File f = LittleFS.open("/dns.cfg", "r");
  if (f) {
    while (f.available() && dnsCount < MAX_DNS) dnsAdd(f.readStringUntil('\n'));
    f.close();
  }
  if (!dnsCount) dnsParseList(UPSTREAM_DNS_LIST);
  if (!dnsCount) {
    dnsList[0] = IPAddress(1, 1, 1, 1);
    dnsCount = 1;
  }
  dnsCur = 0;
  dnsNext = -1;
  upstreamIP = dnsList[0];
}
static void saveDnsCfg() {
  File f = LittleFS.open("/dns.cfg", "w");
  if (!f) return;
  for (int i = 0; i < dnsCount; i++) f.println(dnsList[i].toString());
  f.close();
}
static void applyDnsSwitch() {
  if (dnsNext < 0 || dnsNext >= dnsCount) return;
  if (dnsNext == dnsCur && upstreamIP == dnsList[dnsCur]) {
    dnsNext = -1;
    return;
  }
  if (!dnsIdle()) return; // never strand an in-flight reply
  dnsCur = dnsNext;
  dnsNext = -1;
  upstreamIP = dnsList[dnsCur];
  rttSum = locSum = 0;
  rttCnt = locCnt = 0;
  rttIdx = locIdx = 0; // health belongs to the old server
  for (int i = 0; i < RTT_WINDOW; i++) {
    rttRing[i] = 0;
    locRing[i] = 0;
  }
}
static uint32_t dnsProbeFails = 0; // diagnostics: probe timeouts since boot
static int dnsProbePos = -1;       // server being probed (-1 = idle)
static uint16_t dnsProbeWid = 0;
static uint32_t dnsProbeSent = 0, dnsRoundStart = 0;
static int dnsProbeNext = 0; // next server in the current round
static void sendDnsProbe(int i) {
  uint8_t q[64];
  int n = 12;
  uint16_t wid = (uint16_t)rnd32();
  if (!wid) wid = 1;
  q[0] = wid >> 8;
  q[1] = wid & 0xFF;
  q[2] = 0x01;
  q[3] = 0x00; // RD, one question
  q[4] = 0;
  q[5] = 1;
  q[6] = q[7] = q[8] = q[9] = q[10] = q[11] = 0;
  const char* p = DNS_PROBE_NAME;
  while (*p) {
    const char* dot = strchr(p, '.');
    int l = dot ? (int)(dot - p) : (int)strlen(p);
    if (l <= 0 || l > 63 || n + 1 + l >= (int)sizeof(q)) break;
    q[n++] = (uint8_t)l;
    memcpy(q + n, p, l);
    n += l;
    p += l + (dot ? 1 : 0);
  }
  q[n++] = 0;
  q[n++] = 0;
  q[n++] = 1;
  q[n++] = 0;
  q[n++] = 1; // root, A, IN
  probeCli.beginPacket(dnsList[i], UPSTREAM_PORT);
  probeCli.write(q, n);
  probeCli.endPacket();
  dnsProbeWid = wid;
  dnsProbeSent = millis();
  dnsProbePos = i;
}
static void probeDnsTick() {
  if (dnsCount < 1) return;
  const uint32_t now = millis();
  if (dnsProbePos >= 0) {
    int sz = probeCli.parsePacket();
    if (sz > 0) {
      uint32_t from = (uint32_t)probeCli.remoteIP(); // capture before read/flush
      uint8_t h[96];
      int n = probeCli.read(h, sizeof(h));
      probeCli.flush();
      if (n >= 12 && from == (uint32_t)dnsList[dnsProbePos] &&
          (((h[0] << 8) | h[1]) == dnsProbeWid) && (h[2] & 0x80)) {
        uint32_t r = now - dnsProbeSent;
        if (r > 5000) r = 5000;
        dnsRtt[dnsProbePos] = (uint16_t)r;
        dnsFails[dnsProbePos] = 0;
        dnsProbePos = -1;
      }
    } else if (now - dnsProbeSent > DNS_PROBE_TIMEOUT_MS) {
      probeCli.flush();
      dnsProbeFails++;
      int i = dnsProbePos;
      if (dnsFails[i] < 255) dnsFails[i]++;
      if (dnsFails[i] >= 2) dnsRtt[i] = DNS_DEAD; // two misses in a row = dead
      dnsProbePos = -1;
    }
  }
  if (dnsProbePos >= 0) return;
  if (dnsRoundStart == 0 || (uint32_t)(now - dnsRoundStart) >= DNS_PROBE_INTERVAL_MS) {
    dnsRoundStart = now;
    dnsProbeNext = 0;
  }
  if (dnsProbeNext < dnsCount) {
    sendDnsProbe(dnsProbeNext++);
    return;
  }
  int pick = pickDns(dnsRtt, dnsCount, dnsCur); // round done -> re-evaluate
  if (pick != dnsCur) dnsNext = pick;
}

