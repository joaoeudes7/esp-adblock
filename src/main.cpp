// ---------- WiFi provisioning (SmartConfig / ESP-Touch) ----------
// /wifi.cfg is baked into the LittleFS image by tools/gen_config.py. It takes priority
// over NVS/secrets.h, so re-uploading the filesystem re-provisions without recompiling.
// Format: KEY=VALUE lines (WIFI_SSID, WIFI_PASS, ...).
static bool loadCfgFile(String& ssid, String& pass) {
  File f = LittleFS.open("/wifi.cfg", "r");
  if (!f) return false;
  while (f.available()) {
    String l = f.readStringUntil('\n');
    l.trim();
    if (!l.length() || l.startsWith("#")) continue;
    int eq = l.indexOf('=');
    if (eq < 0) continue;
    String k = l.substring(0, eq);
    k.trim();
    k.toUpperCase();
    String v = l.substring(eq + 1);
    v.trim();
    if (k == "WIFI_SSID") ssid = v;
    else if (k == "WIFI_PASS") pass = v;
    else if (k == "WIFI_IP") cfgIp = v;
    else if (k == "WIFI_GW") cfgGw = v;
    else if (k == "WIFI_DNS") cfgDns = v;
    else if (k == "WIFI_HOST") cfgHost = v;
  }
  f.close();
  return ssid.length() > 0;
}
static bool hasCreds() {
  String a, b;
  if (loadCfgFile(a, b)) return true;
  prefs.begin("wifi", true);
  bool nvs = prefs.getString("ssid", "").length() > 0;
  prefs.end();
  return nvs || (WIFI_SSID && *WIFI_SSID && strcmp(WIFI_SSID, "YOUR_WIFI_SSID") != 0);
}
static bool connectWiFi() {
  String ss, pw;
  const bool fromCfg = loadCfgFile(ss, pw); // /wifi.cfg (baked) wins
  if (!fromCfg) {
    prefs.begin("wifi", true);
    ss = prefs.getString("ssid", "");
    pw = prefs.getString("pass", "");
    prefs.end();
  }
  const char* ssid = ss.length() ? ss.c_str() : WIFI_SSID;
  const char* pass = ss.length() ? pw.c_str() : WIFI_PASS;
  if (!ssid || !*ssid || strcmp(ssid, "YOUR_WIFI_SSID") == 0) return false; // unconfigured
  Serial.printf("WiFi: connecting to \"%s\"%s\n", ssid,
                fromCfg ? " (/wifi.cfg)" : (ss.length() ? " (provisioned)" : " (secrets.h)"));
  WiFi.mode(WIFI_STA);
#if defined(ESP8266)
  WiFi.setSleepMode(WIFI_NONE_SLEEP);
  WiFi.setOutputPower(20.5f); // max TX power (weak-signal links)
#else
  WiFi.setSleep(false);
  WiFi.setTxPower(WIFI_POWER_19_5dBm);
#endif
  // Hostname (so the router's DHCP list and mDNS show 'esp-adblock').
  const char* host = cfgHost.length() ? cfgHost.c_str() : WIFI_HOST;
  if (host && *host) {
#if defined(ESP8266)
    WiFi.hostname(host);
#else
    WiFi.setHostname(host);
#endif
  }
  // Optional static IP (empty -> DHCP).
  const char* ipc = cfgIp.length() ? cfgIp.c_str() : WIFI_IP;
  const char* gwc = cfgGw.length() ? cfgGw.c_str() : WIFI_GW;
  if (ipc && *ipc) {
    IPAddress ip, gw, sub(255, 255, 255, 0), dns;
    if (ip.fromString(ipc) && gw.fromString(gwc)) {
      const char* dc = cfgDns.length() ? cfgDns.c_str() : WIFI_DNS;
      if (!dc || !*dc || !dns.fromString(dc)) dns = IPAddress(1, 1, 1, 1);
      WiFi.config(ip, gw, sub, dns);
      Serial.printf("WiFi: static IP %s gw %s\n", ipc, gwc);
    }
  }
  WiFi.begin(ssid, pass);
  uint32_t t0 = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - t0 < 30000) {
    delay(250);
    Serial.print(".");
  }
  Serial.println();
  return WiFi.status() == WL_CONNECTED;
}

// ESP-Touch / SmartConfig provisioning: the phone app pushes SSID+password over the
// air, so no SoftAP and no portal are needed. The radio runs in STA+promiscuous only
// during this call, so steady-state cost is zero. Same API on ESP8266 and ESP32.
static void serialPump(); // defined with the serial handlers below (keeps serial alive here)

static bool trySmartConfig(uint32_t timeoutMs) {
  WiFi.mode(WIFI_STA);
#if defined(ESP8266)
  WiFi.setSleepMode(WIFI_NONE_SLEEP);
#else
  WiFi.setSleep(false);
#endif
  WiFi.beginSmartConfig();
  Serial.printf("[smartconfig] waiting %lus for the ESP-Touch app...\n", (unsigned long)(timeoutMs / 1000));
  uint32_t t0 = millis();
  while (!WiFi.smartConfigDone() && millis() - t0 < timeoutMs) {
    delay(200);
    Serial.print(".");
    serialPump();
  }
  Serial.println();
  if (!WiFi.smartConfigDone()) {
    WiFi.stopSmartConfig();
    Serial.println("[smartconfig] timeout");
    return false;
  }
  Serial.println("[smartconfig] credentials received, connecting...");
  uint32_t t1 = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - t1 < 20000) {
    delay(200);
    Serial.print(".");
    serialPump();
  }
  Serial.println();
  if (WiFi.status() != WL_CONNECTED) {
    Serial.println("[smartconfig] not connected");
    return false;
  }
  String ss = WiFi.SSID(), pw = WiFi.psk();
  prefs.begin("wifi", false);
  prefs.putString("ssid", ss);
  prefs.putString("pass", pw);
  prefs.end();
  Serial.printf("[smartconfig] saved \"%s\"\n", ss.c_str());
  return true;
}

// ---------- serial provisioning: Improv Wi-Fi (standard) + plain-text CFG ----------
// The browser installer speaks Improv Wi-Fi Serial (https://www.improv-wifi.com/serial/),
// the same protocol used by ESP Web Tools / Tasmota / ESPHome — it supports Wi-Fi scans
// and device info. The plain-text CFG lines are kept as a minimal scripting fallback.
//   CFG ssid <name> / pass / host / ip / gw / dns … then  CFG commit
// Both paths write /wifi.cfg, preserving unrelated keys.

enum ImprovPacket { IMPROV_STATE = 0x01,
                    IMPROV_ERROR = 0x02,
                    IMPROV_RPC = 0x03,
                    IMPROV_RESULT = 0x04 };
enum ImprovCmd {
  IMPROV_CMD_WIFI = 0x01,
  IMPROV_CMD_STATE = 0x02,
  IMPROV_CMD_INFO = 0x03,
  IMPROV_CMD_SCAN = 0x04,
  IMPROV_CMD_HOST = 0x05,
};
enum ImprovStatus { IMPROV_S_READY = 0x02,
                    IMPROV_S_PROVISIONING = 0x03,
                    IMPROV_S_PROVISIONED = 0x04 };
enum ImprovError {
  IMPROV_E_NONE = 0x00,
  IMPROV_E_INVALID = 0x01,
  IMPROV_E_UNKNOWN_CMD = 0x02,
  IMPROV_E_CONNECT = 0x03,
  IMPROV_E_HOSTNAME = 0x05,
};

static uint8_t improvCs;
static void improvStart(uint8_t type, uint8_t len) {
  improvCs = 0;
  const char* m = "IMPROV";
  for (uint8_t i = 0; i < 6; i++) {
    Serial.write((uint8_t)m[i]);
    improvCs += (uint8_t)m[i];
  }
  Serial.write((uint8_t)1);
  improvCs += 1;
  Serial.write(type);
  improvCs += type;
  Serial.write(len);
  improvCs += len;
}
static void improvPut(uint8_t b) {
  Serial.write(b);
  improvCs += b;
}
static void improvPutStr(const char* s) {
  size_t n = strlen(s);
  improvPut((uint8_t)n);
  for (size_t i = 0; i < n; i++) improvPut((uint8_t)s[i]);
}
static void improvFinish() {
  Serial.write(improvCs);
  Serial.write((uint8_t)'\n');
}
static void improvSetState(uint8_t st) {
  improvStart(IMPROV_STATE, 1);
  improvPut(st);
  improvFinish();
}
static void improvError(uint8_t er) {
  improvStart(IMPROV_ERROR, 1);
  improvPut(er);
  improvFinish();
}
static void improvResult(uint8_t rpc, const char* const* strs, uint8_t n) {
  uint8_t total = 0;
  for (uint8_t i = 0; i < n; i++) total += (uint8_t)(1 + strlen(strs[i]));
  improvStart(IMPROV_RESULT, (uint8_t)(2 + total));
  improvPut(rpc);
  improvPut(total);
  for (uint8_t i = 0; i < n; i++) improvPutStr(strs[i]);
  improvFinish();
}

// Merge the credentials into /wifi.cfg; only the provided keys are replaced.
static bool wifiCfgWrite(const String& ssid, const String& pass, const String& host,
                         const String& ip = "", const String& gw = "", const String& dns = "") {
  String keep;
  File rf = LittleFS.open("/wifi.cfg", "r");
  if (rf) {
    while (rf.available()) {
      String old = rf.readStringUntil('\n');
      old.trim();
      if (!old.length()) continue;
      if (old.startsWith("#")) {
        keep += old + "\n";
        continue;
      } // keep comments
      int eq = old.indexOf('=');
      String k = eq > 0 ? old.substring(0, eq) : String("");
      k.trim();
      k.toUpperCase();
      if (k == "WIFI_SSID" || k == "WIFI_PASS" || k == "WIFI_HOST" ||
          k == "WIFI_IP" || k == "WIFI_GW" || k == "WIFI_DNS") continue;
      keep += old + "\n";
    }
    rf.close();
  }
  File wf = LittleFS.open("/wifi.cfg", "w");
  if (!wf) return false;
  wf.print(keep);
  if (ssid.length()) wf.printf("WIFI_SSID=%s\nWIFI_PASS=%s\n", ssid.c_str(), pass.c_str());
  if (host.length()) wf.printf("WIFI_HOST=%s\n", host.c_str());
  if (ip.length()) wf.printf("WIFI_IP=%s\n", ip.c_str());
  if (gw.length()) wf.printf("WIFI_GW=%s\n", gw.c_str());
  if (dns.length()) wf.printf("WIFI_DNS=%s\n", dns.c_str());
  wf.close();
  return true;
}

static bool serialCfgApplied = false; // set once a config was accepted (window ends)

// Persist credentials, then try to connect. Reports state to Improv clients.
static bool applyWifi(const String& ssid, const String& pass, const String& host,
                      const String& ip, const String& gw, const String& dns) {
  if (!ssid.length()) return false;
  if (!wifiCfgWrite(ssid, pass, host, ip, gw, dns)) return false;
  improvSetState(IMPROV_S_PROVISIONING);
  bool ok = connectWiFi();
  improvSetState(ok ? IMPROV_S_PROVISIONED : IMPROV_S_READY);
  if (!ok) improvError(IMPROV_E_CONNECT);
  serialCfgApplied = true;
  return ok;
}

// Try credentials WITHOUT persisting (so a typo can't lock us out of the device).
static bool tryCreds(const String& ssid, const String& pass, uint32_t timeoutMs) {
  WiFi.mode(WIFI_STA);
  WiFi.begin(ssid.c_str(), pass.c_str());
  uint32_t t0 = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - t0 < timeoutMs) delay(150);
  return WiFi.status() == WL_CONNECTED;
}
static void currentCreds(String& ssid, String& pass) {
  if (!loadCfgFile(ssid, pass)) {
    prefs.begin("wifi", true);
    ssid = prefs.getString("ssid", "");
    pass = prefs.getString("pass", "");
    prefs.end();
  }
}
// Change network: verify first; persist only on success, otherwise restore the previous one.
static void handleSetWifi() {
  if (!requireAuth()) return;
  String ssid = web.arg("ssid");
  ssid.trim();
  String pass = web.arg("pass");
  web.sendHeader("Cache-Control", "no-store");
  if (!ssid.length()) {
    web.send(400, "text/plain", "SSID required");
    return;
  }
  String oldS, oldP;
  currentCreds(oldS, oldP); // also fills cfgHost/cfgIp/cfgGw/cfgDns
  String keepHost = cfgHost, keepIp = cfgIp, keepGw = cfgGw, keepDns = cfgDns;
  if (tryCreds(ssid, pass, 15000)) {
    wifiCfgWrite(ssid, pass, keepHost, keepIp, keepGw, keepDns);
    web.send(200, "text/plain", "Joined \"" + ssid + "\" (" + WiFi.localIP().toString() + ")");
  } else {
    if (oldS.length()) tryCreds(oldS, oldP, 15000); // roll back
    web.send(200, "text/plain", "Could not join \"" + ssid + "\". Kept the previous network.");
  }
}

// Blocking scan, single request (the UI fetches once, no polling).
static void handleScan() {
  if (!requireAuth()) return;
  web.sendHeader("Cache-Control", "no-store");
  int n = WiFi.scanNetworks();
  String j = "[";
  for (int i = 0; i < n; i++) {
    String ss = WiFi.SSID(i);
    if (!ss.length()) continue;
    j += (j.length() > 1 ? "," : "");
    j += "{\"s\":\"" + jesc(ss) + "\",\"r\":" + WiFi.RSSI(i) + ",\"e\":" + ((int)WiFi.encryptionType(i) != 0 ? 1 : 0) + "}";
  }
  j += "]";
  WiFi.scanDelete();
  web.send(200, "application/json", j);
}

static String currentHostname() {
  File f = LittleFS.open("/wifi.cfg", "r");
  String hn;
  if (f) {
    while (f.available()) {
      String l = f.readStringUntil('\n');
      l.trim();
      if (l.startsWith("WIFI_HOST=")) hn = l.substring(10);
    }
    f.close();
  }
  hn.trim();
  return hn.length() ? hn : String(WIFI_HOST);
}

static bool netIsOpen(uint8_t i) {
#if defined(ESP8266)
  return WiFi.encryptionType(i) == ENC_TYPE_NONE; // 7 on ESP8266
#else
  return WiFi.encryptionType(i) == WIFI_AUTH_OPEN; // 0 on ESP32 family
#endif
}

// NUL-terminated String from a length-prefixed field (SSID/password/hostname).
static String strSlice(const uint8_t* p, uint8_t n) {
  char b[128];
  if (n > sizeof(b) - 1) n = sizeof(b) - 1;
  memcpy(b, p, n);
  b[n] = 0;
  return String(b);
}

static void improvHandleRPC(const uint8_t* data, uint8_t len) {
  if (len < 2 || data[1] > len - 2) {
    improvError(IMPROV_E_INVALID);
    return;
  } // malformed RPC
  uint8_t cmd = data[0];
  const uint8_t* d = data + 2;
  uint8_t dlen = data[1];
  switch (cmd) {
  case IMPROV_CMD_STATE: { // request current state
    bool up = WiFi.status() == WL_CONNECTED;
    improvSetState(up ? IMPROV_S_PROVISIONED : IMPROV_S_READY);
    if (up) {
      String url = "http://" + WiFi.localIP().toString() + "/";
      const char* r[1] = {url.c_str()};
      improvResult(IMPROV_CMD_STATE, r, 1);
    }
    break;
  }
  case IMPROV_CMD_INFO: { // request device info
    String host = currentHostname();
    const char* info[4] = {"esp-adblock", FW_VERSION, ARDUINO_BOARD, host.c_str()};
    improvResult(IMPROV_CMD_INFO, info, 4);
    break;
  }
  case IMPROV_CMD_SCAN: { // scan Wi-Fi networks
    int n = WiFi.scanNetworks();
    if (n < 0) {
      delay(300);
      n = WiFi.scanNetworks();
    } // WIFI_SCAN_RUNNING -> retry
    for (int i = 0; i < n && i < 24; i++) {
      String ssid = WiFi.SSID(i);
      if (!ssid.length()) continue;
      String rssi = String(WiFi.RSSI(i));
      const char* r[3] = {ssid.c_str(), rssi.c_str(), netIsOpen(i) ? "NO" : "YES"};
      improvResult(IMPROV_CMD_SCAN, r, 3);
    }
    improvResult(IMPROV_CMD_SCAN, nullptr, 0); // empty list = end of scan
    break;
  }
  case IMPROV_CMD_HOST: { // get/set hostname
    if (dlen) {
      String h = strSlice(d, dlen);
      h.trim();
      if (!h.length() || !wifiCfgWrite("", "", h)) {
        improvError(IMPROV_E_HOSTNAME);
        break;
      }
    }
    String host = currentHostname();
    const char* r[1] = {host.c_str()};
    improvResult(IMPROV_CMD_HOST, r, 1);
    break;
  }
  case IMPROV_CMD_WIFI: { // send Wi-Fi settings
    if (dlen < 2) {
      improvError(IMPROV_E_INVALID);
      break;
    }
    uint8_t sl = d[0];
    if ((uint16_t)sl + 2 > dlen) {
      improvError(IMPROV_E_INVALID);
      break;
    }
    String ssid = strSlice(d + 1, sl);
    uint8_t pl = d[1 + sl];
    if ((uint16_t)sl + pl + 2 > dlen) {
      improvError(IMPROV_E_INVALID);
      break;
    }
    String pass = strSlice(d + 2 + sl, pl);
    if (!ssid.length()) {
      improvError(IMPROV_E_INVALID);
      break;
    }
    improvError(IMPROV_E_NONE);
    if (applyWifi(ssid, pass, "", "", "", "")) {
      String url = "http://" + WiFi.localIP().toString() + "/";
      const char* r[1] = {url.c_str()};
      improvResult(IMPROV_CMD_WIFI, r, 1);
    }
    break;
  }
  default:
    improvError(IMPROV_E_UNKNOWN_CMD); // unknown RPC command
  }
}

// Byte pump over the console, shared by both protocols. Improv packets are framed
// ("IMPROV" + version + type + len + data + checksum); anything else is a text line.
static uint8_t sBuf[300];
static uint16_t sLen = 0, sNeed = 0;
static bool sImprov = false;
struct PendCfg {
  String ssid, pass, host, ip, gw, dns;
} pend;

static void handleCfgLine(char* l) {
  if (strncmp(l, "CFG", 3) != 0) return;
  if (strcmp(l, "CFG commit") == 0) {
    if (!pend.ssid.length()) {
      Serial.println("CFGERR missing ssid");
      return;
    }
    bool ok = applyWifi(pend.ssid, pend.pass, pend.host, pend.ip, pend.gw, pend.dns);
    Serial.println(ok ? "CFGSAVED" : "CFGERR connect");
    return;
  }
  char* sp = strchr(l, ' ');
  if (!sp) return;
  *sp = 0;
  char* key = l + 4; // "CFG " is 4 chars
  char* val = sp + 1;
  if (!strcmp(key, "ssid")) pend.ssid = val;
  else if (!strcmp(key, "pass")) pend.pass = val;
  else if (!strcmp(key, "host")) pend.host = val;
  else if (!strcmp(key, "ip")) pend.ip = val;
  else if (!strcmp(key, "gw")) pend.gw = val;
  else if (!strcmp(key, "dns")) pend.dns = val;
}

static void serialFeedByte(uint8_t b) {
  if (!sImprov) {
    if (b == '\n') {
      sBuf[sLen] = 0;
      if (sLen) handleCfgLine((char*)sBuf);
      sLen = 0;
      return;
    }
    if (sLen < sizeof(sBuf) - 1) sBuf[sLen++] = b;
    else sLen = 0;
    if (sLen == 9 && memcmp(sBuf, "IMPROV", 6) == 0) {
      sImprov = true;
      sNeed = 9 + sBuf[8] + 1;
    }
    return;
  }
  if (sLen < sizeof(sBuf) - 1) sBuf[sLen++] = b;
  if (sLen >= sNeed) {
    uint8_t cs = 0;
    for (uint16_t i = 0; i + 1 < sNeed; i++) cs += sBuf[i];
    if (sBuf[6] == 1 && cs == sBuf[sNeed - 1] && sBuf[7] == IMPROV_RPC)
      improvHandleRPC(sBuf + 9, sBuf[8]);
    else
      improvError(IMPROV_E_INVALID);
    sLen = 0;
    sImprov = false;
    sNeed = 0;
  }
}

static void serialPump() {
  while (Serial.available()) serialFeedByte((uint8_t)Serial.read());
}

static bool serialProvision(uint32_t windowMs) {
  pend = PendCfg();
  Serial.printf("[provision] serial window %lus (Improv Wi-Fi + CFG lines)\n", (unsigned long)(windowMs / 1000));
  Serial.println("CFGREADY");
  improvSetState(WiFi.status() == WL_CONNECTED ? IMPROV_S_PROVISIONED : IMPROV_S_READY);
  uint32_t t0 = millis();
  while (!serialCfgApplied && millis() - t0 < windowMs) {
    if (!Serial.available()) {
      delay(5);
      continue;
    }
    serialPump();
  }
  if (!serialCfgApplied) Serial.println("CFGTIMEOUT");
  return serialCfgApplied;
}

// Runtime WiFi watchdog: if the link drops, reconnect with a growing backoff capped at 30 s.
static void wifiWatchdog() {
  if (WiFi.status() == WL_CONNECTED) {
    wifiDownSince = 0;
    lastReconn = 0;
    reconnAttempts = 0;
    return;
  }
  uint32_t now = millis();
  if (!wifiDownSince) {
    wifiDownSince = now;
    lastReconn = now;
    return;
  }
  uint32_t backoff = (reconnAttempts > 5) ? 30 : (1u << reconnAttempts); // 1,2,4,8,16,30(cap)
  if (backoff > 30) backoff = 30;
  if ((uint32_t)(now - lastReconn) >= backoff * 1000UL) {
    lastReconn = now;
    if (reconnAttempts < 15) reconnAttempts++;
    Serial.printf("[wifi] down %lus — reconnect (backoff %lus)\n",
                  (unsigned long)((now - wifiDownSince) / 1000), (unsigned long)backoff);
    WiFi.reconnect();
  }
}

void setup() {
  Serial.begin(115200);
  delay(300);
  pinMode(LED_PIN, OUTPUT);
  digitalWrite(LED_PIN, LED_ON); // LED on while booting/initializing
  Serial.println("\n[esp-adblock] booting");
#if defined(ESP8266)
  if (!LittleFS.begin()) {
    LittleFS.format();
    LittleFS.begin();
  }
#else
  if (!LittleFS.begin(true)) Serial.println("LittleFS FAILED");
#endif
  reopenBlocklist();
  Serial.printf("blocklist: %u domains\n", (unsigned)numHashes);
  loadRules();
  loadHosts();
  loadNames();
  loadBlockCfg();
  loadProxyCfg();
  loadStats();
  loadDnsCfg();
  {
    File f = LittleFS.open("/boot.cnt", "r");
    if (f) {
      bootId = f.readStringUntil('\n').toInt();
      f.close();
    }
    bootId = bootDbgInit(bootId + 1); // no-op unless BOOT_DEBUG; may adopt a recorded id
    f = LittleFS.open("/boot.cnt", "w");
    if (f) {
      f.println(bootId);
      f.close();
    }
  }
  Serial.printf("rules: block=%d allow=%d keyword=%d\n", numBlock, numAllow, numKw);

  // Hold BOOT at power-on to wipe saved WiFi and force re-provisioning (SmartConfig).
#if defined(ESP8266)
  const int BOOT_PIN = 0; // ESP8266 BOOT / GPIO0
#elif CONFIG_IDF_TARGET_ESP32C3
  const int BOOT_PIN = 9; // C3 BOOT button
#else
  const int BOOT_PIN = 0; // classic ESP32 BOOT button (GPIO9 is a flash pin there)
#endif
  pinMode(BOOT_PIN, INPUT_PULLUP);
  if (digitalRead(BOOT_PIN) == LOW) {
    delay(60);
    if (digitalRead(BOOT_PIN) == LOW) {
      prefs.begin("wifi", false);
      prefs.clear();
      prefs.end();
      Serial.println("[setup] BOOT held -> cleared saved WiFi");
    }
  }

  if (!connectWiFi()) {
    if (!hasCreds()) {
      // No credentials: accept the browser installer's serial config, or ESP-Touch.
      // Short windows so whichever source arrives first is handled promptly.
      serialCfgApplied = false;
      for (;;) {
        if (serialProvision(10000)) {
          Serial.println("[provision] /wifi.cfg written");
          break;
        }
        if (trySmartConfig(10000)) break;
        if (WiFi.status() == WL_CONNECTED) break; // config arrived while ESP-Touch was listening
        Serial.println("[provision] retry — serial CFG lines or the ESP-Touch app");
      }
      if (!connectWiFi()) {
        Serial.println("[provision] still not connected; rebooting in 10s");
        bootDbgMarkRestart(BOOT_INTENT_PROVISION);
        delay(10000);
        ESP.restart();
      }
      Serial.printf("WiFi up: %s\n", WiFi.localIP().toString().c_str());
    } else {
      // Creds exist but the link is down (router off?): reboot and retry.
      Serial.println("[setup] saved WiFi didn't connect; rebooting in 30s");
      bootDbgMarkRestart(BOOT_INTENT_PROVISION);
      delay(30000);
      ESP.restart();
    }
  }
  Serial.printf("WiFi up: %s\n", WiFi.localIP().toString().c_str());
  if (MDNS.begin("esp-adblock")) {
    MDNS.addService("http", "tcp", 80);
    Serial.println("dashboard: http://esp-adblock.local");
  }

  if (strcmp(WEB_PASS, "change-me-please") == 0)
    Serial.println("[WARN] secrets.h still has a placeholder WEB_PASS — set a real value "
                   "(config.env) before trusting this device on a network you don't fully control.");

  dnsServer.begin(DNS_PORT);
  upstreamCli.begin(0);
  probeCli.begin(0);
  tcpDns.begin();
  tcpDns.setNoDelay(true); // TCP :53 fallback for truncated UDP replies
  tcpRelay.begin(tcpDns, upstreamIP, DNS_PORT, tcpBuf, sizeof(tcpBuf), tcpResolve, tcpReplied, nullptr);
  blackhole.begin();       // drop PAC-routed URL matches (see /proxy.pac)
#if defined(ESP8266)
  web.collectHeaders(CSRF_HEADER); // ESP8266 variadic overload; a char*[] picks the wrong template
#else
  {
    const char* hdrs[] = {CSRF_HEADER};
    web.collectHeaders(hdrs, 1);
  } // needed for requireAuth()'s CSRF check
#endif
  web.on("/", handleRoot); // dashboard, or block page for a sinkholed host
  web.on("/stats.json", handleStats);
  web.on("/events", handleEvents);                                    // recent-blocked ring (frontend keeps history)
  web.on("/world.svg", handleWorldSvg);                               // static map for the destination card
  web.on("/__dnscheck", []() { web.send(200, "text/plain", "ok"); }); // resolver-usage probe (see lookupHost)
  web.on("/allow", handleAllow);                                      // block-page "continue" (CSRF-gated, no Basic auth)
  web.on("/setblock", handleSetBlock);                                // blocked-reply mode (ip/zero/nxdomain)
  web.on("/setdns", []() {                                            // upstream candidates (comma/space/newline separated)
    if (!requireAuth()) return;
    String csv = web.arg("d");
    if (!dnsParseList(csv)) {
      web.send(400, "text/plain", "bad list: need 1-4 IPv4 addresses");
      return;
    }
    saveDnsCfg();
    dnsCur = 0;
    dnsNext = 0; // applied when no query is in flight
    dnsRoundStart = 0;
    dnsProbeNext = 0; // probe the new list right away
    web.send(200, "text/plain", "ok");
  });
  web.on("/proxy.pac", HTTP_GET, handlePac); // auto-proxy config (no auth: OS/browser fetch)
  web.on("/wpad.dat", HTTP_GET, handlePac);  // WPAD alias (DNS answers "wpad" -> this device)
  web.on("/dns-query", HTTP_GET, handleDoh); // DoH (RFC 8484) over plain HTTP; no TLS
  web.on("/dns-query", HTTP_POST, handleDoh);
  web.on("/setproxy", handleSetProxy);       // set the PAC proxy (host:port)
  web.on("/sethost", handleSetHost);         // local DNS record add/replace
  web.on("/delhost", handleDelHost);         // local DNS record remove
  web.on("/addblock", []() { if (!requireAuth()) return; String d = web.arg("d"); if (d.indexOf('*') >= 0) addWild(d); else addBlock(d); web.send(200, "text/plain", "ok"); });
  web.on("/unblock", []() { if (!requireAuth()) return; String d = web.arg("d"); removeBlock(d); removeWild(d); web.send(200, "text/plain", "ok"); });
  web.on("/delallow", []() { if (!requireAuth()) return; removeAllow(web.arg("d"));   web.send(200, "text/plain", "ok"); });
  web.on("/addkeyword", []() { if (!requireAuth()) return; addKeyword(web.arg("t"));   web.send(200, "text/plain", "ok"); });
  web.on("/delkeyword", []() { if (!requireAuth()) return; removeKeyword(web.arg("t")); web.send(200, "text/plain", "ok"); });
  // Raw /rules.cfg read + replace (the whole file); loadRules() reparses after a write.
  web.on("/rules", HTTP_GET, []() { if (!requireAuth()) return; File f = LittleFS.open("/rules.cfg", "r"); String s = f ? f.readString() : String(""); if (f) f.close(); web.send(200, "text/plain", s); });
  web.on("/rules", HTTP_POST, []() {
    if (!requireAuth()) return;
    String body = web.arg("plain");
    noteHeap(1); // a pasted rules file doubles in RAM (arg + copy): the one user-driven OOM path
    int cb = 0, ca = 0, ck = 0, cw = 0, cu = 0; // count per kind before writing
    for (int start = 0; start <= (int)body.length();) {
      int nl = body.indexOf('\n', start);
      if (nl < 0) nl = body.length();
      String l = body.substring(start, nl);
      l.trim();
      start = nl + 1;
      if (!l.length() || l[0] == '#') continue;
      if (l.startsWith("@@||")) {
        ca++;
        continue;
      }
      bool wild = l.indexOf('*') >= 0;
      if (l.startsWith("||")) {
        if (wild) cw++;
        else cb++;
        continue;
      }
      int sp = l.indexOf(' ');
      String verb = (sp < 0) ? l : l.substring(0, sp);
      verb.toLowerCase();
      if (verb == "block" || verb == "b") {
        if (wild) cw++;
        else cb++;
      } else if (verb == "allow" || verb == "a") ca++;
      else if (verb == "keyword" || verb == "k") ck++;
      else if (verb == "wildcard" || verb == "w") cw++;
      else if (verb == "url" || verb == "u") cu++;
    }
    if (cb > MAX_CUSTOM || ca > MAX_ALLOW || ck > MAX_KW || cw > MAX_WILD || cu > MAX_URL) {
      web.send(400, "text/plain", String("too many rules (max block=") + MAX_CUSTOM + " allow=" + MAX_ALLOW + " keyword=" + MAX_KW + " wildcard=" + MAX_WILD + " url=" + MAX_URL + "); not saved");
      return;
    }
    File f = LittleFS.open("/rules.cfg", "w");
    if (f) {
      f.print(body);
      f.close();
    }
    loadRules();
    web.send(200, "text/plain", "ok");
  });
  web.on("/pause", []() { // /pause?s=300  (0 or absent = indefinite)
    if (!requireAuth()) return;
    long s = web.hasArg("s") ? web.arg("s").toInt() : 0;
    blockingOn = false;
    resumeAt = (s > 0) ? millis() + (uint32_t)s * 1000UL : 0;
    web.send(200, "text/plain", "paused");
  });
  web.on("/resume", []() { if (!requireAuth()) return; blockingOn = true; resumeAt = 0; web.send(200, "text/plain", "resumed"); });
  web.on("/setwifi", handleSetWifi);                                // change network (verify, then persist)
  web.on("/scan", handleScan);                                      // nearby networks for the picker
  web.on("/upload", HTTP_POST, handleUploadDone, handleUpload);     // blocklist OTA (auth inside handleUpload)
  web.on("/update", HTTP_POST, handleFwUpdateDone, handleFwUpload); // firmware OTA (auth inside handleFwUpload)
  web.on("/resetstats", []() { if (!requireAuth()) return; resetStats(); web.send(200, "text/plain", "ok"); });
  web.on("/setname", []() { if (!requireAuth()) return; bool ok = setClientName(web.arg("ip").c_str(), web.arg("n")); web.send(ok ? 200 : 400, "text/plain", ok ? "ok" : "bad ip/name"); });
  web.on("/pauseclient", []() { // per-client pause: /pauseclient?ip=1.2.3.4&s=3600 (s=0 clears)
    if (!requireAuth()) return;
    IPAddress ip;
    if (!ip.fromString(web.arg("ip"))) {
      web.send(400, "text/plain", "bad ip");
      return;
    }
    long s = web.hasArg("s") ? web.arg("s").toInt() : 3600;
    if (s < 0) s = 0;
    if (s > 86400) s = 86400;
    Dev* c = nullptr;
    for (int i = 0; i < numClients; i++)
      if (clients[i].ip == (uint32_t)ip) {
        c = &clients[i];
        break;
      }
    if (!c) {
      web.send(404, "text/plain", "unknown ip");
      return;
    }
    c->pausedUntil = s ? millis() + (uint32_t)s * 1000UL : 0;
    web.send(200, "text/plain", "ok");
  });
  web.onNotFound(handleNotFound); // sinkholed hosts -> block page
  web.begin();
  ArduinoOTA.setHostname("esp-adblock"); // pio run -t upload --upload-port esp-adblock.local
  ArduinoOTA.setPassword(WEB_PASS);      // OTA uses the dashboard credential — no separate OTA password
  ArduinoOTA.begin();
  Serial.println("DNS :53 + dashboard :80 + OTA up");
  digitalWrite(LED_PIN, LED_OFF); // ready: LED now off, and blinks only on a blocked lookup
}

void loop() {
  uint32_t _l = micros();
  static uint32_t _prev = 0;
  if (_prev && _l - _prev > stMaxGap) stMaxGap = _l - _prev;
  _prev = _l;
  ArduinoOTA.handle();
  wifiWatchdog();
#if !defined(ESP8266)
  confirmOtaIfSettled();
#endif
  uint32_t _d0 = micros();
  bool busy = handleDns(); // DNS first (latency-sensitive)
  uint32_t _dd = micros() - _d0;
  if (_dd > stMaxDns) stMaxDns = _dd;
  pollUpstream();                                      // relay any upstream replies for in-flight queries
  noteHeap(2);                                         // low-water mark attributed to the DNS path
  probeDnsTick();                                      // non-blocking latency sweep (own UDP socket)
  applyDnsSwitch();                                    // only when nothing is in flight
  uint32_t _t0 = micros();
  tcpRelay.poll(); // TCP :53 fallback (one incremental step; the connect is the only bounded stall)
  uint32_t _td = micros() - _t0;
  if (_td > stMaxTcp) stMaxTcp = _td;
  handleBlackhole();                                   // drop PAC-routed URL matches
  if (!busy || (uint32_t)(millis() - lastWeb) > 100) { // web only when idle (anti-starvation cap)
    lastWeb = millis();
    uint32_t _w0 = micros();
    web.handleClient();
    uint32_t _ww = micros() - _w0;
    if (_ww > stMaxWeb) stMaxWeb = _ww;
    noteHeap(1); // low-water mark attributed to a web request (bursts of these are the OOM risk)
  }
#if defined(ESP8266)
  MDNS.update();
#endif
  if (!blockingOn && resumeAt && (int32_t)(millis() - resumeAt) >= 0) {
    blockingOn = true;
    resumeAt = 0;
  }
  bootDbgTick(WiFi.status() == WL_CONNECTED); // no-op unless BOOT_DEBUG (SNTP + /boot.cfg)
  cpu_gov::checkIdle();              // CPU governor: ondemand (self-throttled)
  // Deferred flash write: never from a handler, never with a query/TCP job in flight (a
  // write disables the flash cache and would land inside the DNS path). The 30 s fallback
  // keeps a permanently busy resolver from deferring the counters forever.
  static uint32_t statsPendingAt = 0;
  static bool statsPending = false;
  if (statsSaveReq.pending() && !statsPending) {
    statsPending = true;
    statsPendingAt = millis();
  }
  bool flashIdle = !busy && !tcpRelay.active() && dnsIdle();
  bool flashStale = statsPending && (uint32_t)(millis() - statsPendingAt) >= 30000UL;
  if (statsPending && (flashIdle || flashStale)) {
    statsSaveReq.take();
    statsPending = false;
    saveStats();
  }
  static uint32_t lastStatsSave = 0; // mark for persistence every ~5 min (only if changed)
  if ((uint32_t)(millis() - lastStatsSave) >= 300000UL) {
    lastStatsSave = millis();
    uint32_t gsum = gafamCnt[0] + gafamCnt[1] + gafamCnt[2] + gafamCnt[3] + gafamCnt[4] + gafamCnt[5];
    if (totalBlocked != savedBlocked || totalAllowed != savedAllowed || totalCached != savedCached ||
        gsum != savedGafam || dnssecSeen != savedDnssec || secPages != savedSecPages ||
        pagesServed != savedPagesServed)
      statsSaveReq.mark();
  }
  if (ledUntil && (int32_t)(millis() - ledUntil) >= 0) {
    digitalWrite(LED_PIN, LED_OFF);
    ledUntil = 0;
  }                    // status LED off
  if (!busy) delay(1); // sleep only when idle: full speed under load, cool when quiet
}
