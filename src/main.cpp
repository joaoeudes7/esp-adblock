// First boot on this format: fold the old /custom.txt + /allow.txt into /rules.cfg and
// seed the default keywords. One-time; afterwards /rules.cfg is the source of truth.
static void migrateRules() {
  File f = LittleFS.open("/custom.txt", "r");
  if (f) { while (f.available()) { String l = f.readStringUntil('\n'); l.trim(); addBlock(l, false); } f.close(); }
  f = LittleFS.open("/allow.txt", "r");
  if (f) { while (f.available()) { String l = f.readStringUntil('\n'); l.trim(); addAllow(l, false); } f.close(); }
  for (size_t i = 0; i < sizeof(KW_DEFAULT) / sizeof(KW_DEFAULT[0]); i++) addKeyword(KW_DEFAULT[i], false);
  saveRules();
  Serial.println("rules: migrated old files + default keywords -> /rules.cfg");
}
static void loadRules() {
  numBlock = numAllow = numKw = 0;
  File f = LittleFS.open("/rules.cfg", "r");
  if (!f) { migrateRules(); return; }
  while (f.available()) {
    String l = f.readStringUntil('\n'); l.trim();
    if (!l.length() || l[0] == '#') continue;
    if (l.startsWith("@@||")) { addAllow(l.substring(4), false); continue; }   // AdBlock shorthand
    if (l.startsWith("||"))   { addBlock(l.substring(2), false); continue; }
    int sp = l.indexOf(' ');
    String verb = (sp < 0) ? l : l.substring(0, sp); verb.toLowerCase();
    String val  = (sp < 0) ? String("") : l.substring(sp + 1); val.trim();
    if (verb == "block" || verb == "b") addBlock(val, false);
    else if (verb == "allow" || verb == "a") addAllow(val, false);
    else if (verb == "keyword" || verb == "k") addKeyword(val, false);
  }
  f.close();
}

