// Encrypted-DNS (DoH/DoT) endpoints a client might use to bypass this sinkhole. We block them
// (they're in the DoH lists) AND count the attempts, so the admin sees an encrypted-DNS bypass.
static const char* const DOH_HOSTS[] = {
    "dns.google", "dns.google.com", "cloudflare-dns.com", "mozilla.cloudflare-dns.com",
    "dns.quad9.net", "doh.opendns.com", "doh.dns.sb", "dns.adguard.com", "dns.adguard-dns.com",
    "doh.cleanbrowsing.org", "dns.nextdns.io", "doh.nextdns.io", "dns.comss.one",
    "dns.digitale-gesellschaft.ch", "dnsforge.de", "doh.li", "doh.applied-privacy.net",
    "doh.ffmuc.net", "doh.mullvad.net", "dns.mullvad.net", "doh.centraleu.pi-dns.com"};
static bool isDohHost(const char* d) {
  const char* p = d;
  while (p && *p) {
    for (size_t i = 0; i < sizeof(DOH_HOSTS) / sizeof(DOH_HOSTS[0]); i++)
      if (strcasecmp(p, DOH_HOSTS[i]) == 0) return true;
    const char* dot = strchr(p, '.');
    if (!dot) break;
    const char* next = dot + 1;
    if (!strchr(next, '.')) break;
    p = next;
  }
  return false;
}
static bool isBlocked(const char* domain) {
  // A runtime allow (exact or parent) or a built-in connectivity check overrides everything.
  const char* a = domain;
  while (a && *a) {
    if (isAllowDomain(a) || isDefaultAllow(a) || isTempAllowed(a)) return false;
    const char* ad = strchr(a, '.');
    if (!ad) break;
    const char* an = ad + 1;
    if (!strchr(an, '.')) break;
    a = an;
  }
  const char* p = domain;
  while (p && *p) {
    if (isBlockDomain(p)) return true;
    if (isDefaultBlock(p)) return true;
    if (isBlockedHash(fnv64(p, strlen(p)))) return true;
    const char* dot = strchr(p, '.');
    if (!dot) break;
    const char* next = dot + 1;
    if (!strchr(next, '.')) break;
    p = next;
  }
  if (isWildBlock(domain)) return true; // wildcard rules match the full host once
  // Opt-in keyword heuristic (fallback; only when the lists didn't match).
  if (keywordBlock && keywordHit(domain)) return true;
  return false;
}

