// ---------- hashing / matching ----------
// ---------- Bloom membership ----------
// Bits live in flash after BLOCKLIST_HDR; memory is O(1) in the domain count.
// k probes via Kirsch-Mitzenmacher: idx_i = (a + i*b) mod m, a/b = the two 32-bit
// halves of a full FNV-1a — same construction as tools/build_bloom.py.
static uint64_t fnv64(const char* s, size_t n) {
  uint64_t h = 0xcbf29ce484222325ULL;
  for (size_t i = 0; i < n; i++) { h ^= (uint8_t)s[i]; h *= 0x100000001b3ULL; }
  return h;
}
static void buildFlashIndex() { for (int i = 0; i < CACHE_SIZE; i++) cacheValid[i] = 0; }
static inline uint8_t bloomBit(uint32_t bit) {
  stBloomSeeks++;
  if (!blocklist.seek(BLOCKLIST_HDR + (bit >> 3))) return 0;
  uint8_t b = 0; blocklist.read(&b, 1);
  return (b >> (bit & 7)) & 1;
}
static bool inFlash(uint64_t h) {
  if (bloomM == 0) return false;
  uint32_t a = (uint32_t)(h >> 32), b = (uint32_t)h;
  for (uint8_t i = 0; i < BLOOM_K; i++) {
    uint32_t bit = (uint32_t)(a + (uint32_t)i * b) % bloomM;
    if (!bloomBit(bit)) return false;   // short-circuit on the first zero bit
  }
  return true;
}

static bool isAllowDomain(const char* d);   // defined with the other persistence helpers

// User blocklist (from /rules.cfg "block <domain>"): matched against each label suffix
// by the caller, so a rule for example.com also blocks ads.example.com.
static bool isBlockDomain(const char* d) {
  for (int i = 0; i < numBlock; i++) if (strcmp(blockDom[i].c_str(), d) == 0) return true;
  return false;
}
static bool isBlockedHash(uint64_t h) {
  stBlkChecks++;
  uint32_t slot = (uint32_t)h & (CACHE_SIZE - 1);
  if (cacheValid[slot] && cacheKey32[slot] == (uint32_t)h) { stBlkHits++; return cacheRes[slot] != 0; }
  bool res = inFlash(h);
  cacheValid[slot] = 1;
  cacheKey32[slot] = (uint32_t)h;
  cacheRes[slot] = res ? 1 : 0;
  return res;
}

// Keyword heuristic: match whole labels (split on '.' and '-') against the user's
// keyword rules (/rules.cfg "keyword <t>"), plus the "ads" prefix. Whole-label only,
// so "downloads" is safe. KW_DEFAULT seeds /rules.cfg on first boot.
static const char* const KW_DEFAULT[] = {
  "ads", "ad", "adserver", "adservice", "adserv", "adtech", "adnxs", "adcolony", "adform",
  "adition", "adroll", "adsrv", "adsrvr", "doubleclick", "pagead", "syndication",
  "analytics", "tracker", "trackers", "tracking", "track", "telemetry", "beacon", "pixel",
  "moatads", "outbrain", "taboola", "criteo", "scorecardresearch", "quantserve",
  "applovin", "appsflyer", "adjust", "kochava", "amplitude", "mixpanel", "hotjar",
  "fullstory", "mouseflow", "luckyorange", "newrelic", "optimizely", "demdex",
  "everesttech", "teads", "adobedtm"
};
static bool keywordHit(const char* d) {
  char buf[256]; size_t n = strlen(d); if (n >= sizeof(buf)) n = sizeof(buf) - 1;
  memcpy(buf, d, n); buf[n] = 0;
  for (char* p = buf; *p; ) {
    char* start = p;
    while (*p && *p != '.' && *p != '-') p++;
    char save = *p; *p = 0;
    if (strncmp(start, "ads", 3) == 0) return true;
    for (int i = 0; i < numKw; i++) if (strcmp(start, kwDom[i].c_str()) == 0) return true;
    if (save == 0) break;
    p++;
  }
  return false;
}
static bool isBlocked(const char* domain) {
  // A runtime allow (exact or parent) overrides everything — the block page adds these.
  const char* a = domain;
  while (a && *a) {
    if (isAllowDomain(a)) return false;
    const char* ad = strchr(a, '.'); if (!ad) break;
    const char* an = ad + 1; if (!strchr(an, '.')) break; a = an;
  }
  const char* p = domain;
  while (p && *p) {
    if (isBlockDomain(p)) return true;
    if (isBlockedHash(fnv64(p, strlen(p)))) return true;
    const char* dot = strchr(p, '.'); if (!dot) break;
    const char* next = dot + 1; if (!strchr(next, '.')) break; p = next;
  }
  // Opt-in keyword heuristic (fallback; only when the lists didn't match).
  if (keywordBlock && keywordHit(domain)) return true;
  return false;
}

