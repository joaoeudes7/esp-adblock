static void saveNames() {
  File f = LittleFS.open("/names.cfg", "w");
  if (!f) return;
  for (int i = 0; i < numNames; i++) {
    IPAddress ip(clientNames[i].ip);
    f.println(ip.toString() + " " + clientNames[i].name);
  }
  f.close();
}
static void loadNames() {
  numNames = 0;
  File f = LittleFS.open("/names.cfg", "r");
  if (!f) return;
  while (f.available() && numNames < MAX_NAMES) {
    String l = f.readStringUntil('\n');
    l.trim();
    if (!l.length()) continue;
    int sp = l.indexOf(' ');
    if (sp <= 0) continue;
    IPAddress ip;
    if (ip.fromString(l.substring(0, sp))) {
      clientNames[numNames].ip = (uint32_t)ip;
      clientNames[numNames].name = l.substring(sp + 1);
      clientNames[numNames].name.trim();
      numNames++;
    }
  }
  f.close();
}
static bool setClientName(const char* ips, String name) {
  IPAddress ip;
  if (!ip.fromString(ips)) return false;
  name.trim();
  if (name.length() > 31) name = name.substring(0, 31);
  for (int i = 0; i < numNames; i++)
    if (clientNames[i].ip == (uint32_t)ip) {
      if (name.length()) clientNames[i].name = name;
      else {
        for (int j = i; j < numNames - 1; j++) clientNames[j] = clientNames[j + 1];
        numNames--;
      }
      saveNames();
      return true;
    }
  if (!name.length() || numNames >= MAX_NAMES) return false;
  clientNames[numNames].ip = (uint32_t)ip;
  clientNames[numNames].name = name;
  numNames++;
  saveNames();
  return true;
}
static String jesc(const String& s) {
  String o;
  for (char ch : s) {
    if ((uint8_t)ch < 0x20) continue;
    if (ch == '"' || ch == '\\') o += '\\';
    o += ch;
  }
  return o;
}
// HTML escape for the block page: the Host header is attacker-controllable.
static String htmlEscape(const String& s) {
  String o;
  o.reserve(s.length());
  for (char ch : s) {
    switch (ch) {
    case '&':
      o += "&amp;";
      break;
    case '<':
      o += "&lt;";
      break;
    case '>':
      o += "&gt;";
      break;
    case '"':
      o += "&quot;";
      break;
    case '\'':
      o += "&#39;";
      break;
    default:
      o += ch;
    }
  }
  return o;
}

