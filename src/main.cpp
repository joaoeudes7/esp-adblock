static void getMac(uint32_t ip, uint8_t* mac) {
  memset(mac, 0, 6);
  ip4_addr_t ipa; ipa.addr = ip;
  struct eth_addr* eth = nullptr; const ip4_addr_t* ipret = nullptr;
  for (struct netif* nif = netif_list; nif; nif = nif->next)
    if (etharp_find_addr(nif, &ipa, &eth, &ipret) >= 0 && eth) { memcpy(mac, eth->addr, 6); return; }
}
static Dev* getClient(uint32_t ip) {
  for (int i = 0; i < numClients; i++) if (clients[i].ip == ip) { clients[i].lastSeen = millis(); return &clients[i]; }
  if (numClients < MAX_CLIENTS) {
    Dev* c = &clients[numClients++];
    c->ip = ip; c->blocked = c->allowed = 0; c->lastSeen = millis(); c->qps = 0; c->win = 0; c->label = "";
    getMac(ip, c->mac); return c;
  }
  int oldest = 0;                                   // full: evict the least-recently-seen
  for (int i = 1; i < numClients; i++) if (clients[i].lastSeen < clients[oldest].lastSeen) oldest = i;
  Dev* c = &clients[oldest];
  c->ip = ip; c->blocked = c->allowed = 0; c->lastSeen = millis(); c->qps = 0; c->win = 0; c->label = "";
  getMac(ip, c->mac); return c;
}

