// Minimal Preferences-compatible shim: 2x96-byte strings in EEPROM (ssid/pass).
class Preferences {
public:
  void begin(const char* ns, bool ro = false) {
    (void)ns;
    _ro = ro;
    if (!_begun) {
      EEPROM.begin(512);
      _begun = true;
    }
  }
  void end() {}
  String getString(const char* key, const char* dflt) {
    char b[96];
    EEPROM.get(_off(key), b);
    b[95] = 0;
    if (b[0] == 0 || (uint8_t)b[0] == 0xFF) return String(dflt);
    return String(b);
  }
  void putString(const char* key, const String& v) {
    char b[96];
    memset(b, 0, sizeof(b));
    v.toCharArray(b, sizeof(b));
    EEPROM.put(_off(key), b);
    EEPROM.commit();
  }
  void clear() {
    for (int i = 0; i < 512; i++) EEPROM.write(i, 0);
    EEPROM.commit();
  }

private:
  bool _ro = false, _begun = false;
  int _off(const char* k) { return strcmp(k, "ssid") == 0 ? 0 : 96; }
};
