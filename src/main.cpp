static void loadRules() {
  numBlock = numAllow = numKw = numWild = 0;
  File f = LittleFS.open("/rules.cfg", "r");
  if (!f) {
    migrateRules();
    return;
  }
  while (f.available()) {
    String l = f.readStringUntil('\n');
    l.trim();
    if (!l.length() || l[0] == '#') continue;
    if (l.startsWith("@@||")) {
      addAllow(l.substring(4), false);
      continue;
    } // AdBlock shorthand
    if (l.startsWith("||")) {
      String d = l.substring(2);
      if (d.indexOf('*') >= 0) addWild(d, false);
      else addBlock(d, false);
      continue;
    }
    int sp = l.indexOf(' ');
    String verb = (sp < 0) ? l : l.substring(0, sp);
    verb.toLowerCase();
    String val = (sp < 0) ? String("") : l.substring(sp + 1);
    val.trim();
    if (verb == "block" || verb == "b") {
      if (val.indexOf('*') >= 0) addWild(val, false);
      else addBlock(val, false);
    } else if (verb == "allow" || verb == "a") addAllow(val, false);
    else if (verb == "keyword" || verb == "k") addKeyword(val, false);
    else if (verb == "wildcard" || verb == "w") addWild(val, false);
  }
  f.close();
}

