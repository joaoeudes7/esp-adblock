// The dashboard requires Basic auth: navigation makes the browser prompt for WEB_PASS,
// and the browser then attaches the cached credentials to the page's own fetch() calls
// (a fetch()/XHR 401 does NOT show the prompt itself, so the page must demand it).
static void handleRoot() {
  String host; if (foreignHost(host)) { serveSinkhole(host); return; }
  if (!web.authenticate(WEB_USER, WEB_PASS)) { web.requestAuthentication(); return; }
  web.sendHeader("Cache-Control", "no-store");
  web.send_P(200, "text/html", PAGE);
}
static void handleNotFound() {
  String host; if (foreignHost(host)) { serveSinkhole(host); return; }
  web.send(404, "text/plain", "not found");
}

// ---------- blocklist swap (shared by upload + remote fetch) ----------
static void reopenBlocklist() {
  blocklist = LittleFS.open(BLOCKLIST_PATH, "r");
  numHashes = 0; bloomM = 0;
  if (blocklist) {
    uint8_t hdr[BLOCKLIST_HDR];
    if (blocklist.read(hdr, BLOCKLIST_HDR) == BLOCKLIST_HDR &&
        hdr[0] == 'B' && hdr[1] == 'L' && hdr[2] == 'M' && hdr[3] == '1') {
      numHashes = (uint32_t)hdr[4] | ((uint32_t)hdr[5] << 8) | ((uint32_t)hdr[6] << 16) | ((uint32_t)hdr[7] << 24);
      bloomM = (uint32_t)((blocklist.size() - BLOCKLIST_HDR) * 8);
    } else {
      Serial.println("[bloom] bad header — blocklist ignored");
    }
  }
  buildFlashIndex();
}
static void beginBlocklistSwap() {
  if (blocklist) blocklist.close();
  numHashes = 0;
  LittleFS.remove(BLOCKLIST_PATH);
  LittleFS.remove("/blocklist.new");
}
static bool commitNewBlocklist() {                  // /blocklist.new -> live (validated)
  File f = LittleFS.open("/blocklist.new", "r");
  size_t sz = f ? f.size() : 0;
  bool ok = false;
  if (f && sz > BLOCKLIST_HDR) {                    // validate the 'BLM1' magic before swapping
    uint8_t hdr[BLOCKLIST_HDR];
    ok = f.read(hdr, BLOCKLIST_HDR) == BLOCKLIST_HDR && hdr[0] == 'B' && hdr[1] == 'L' && hdr[2] == 'M' && hdr[3] == '1';
  }
  if (f) f.close();
  if (ok) LittleFS.rename("/blocklist.new", BLOCKLIST_PATH);
  else    LittleFS.remove("/blocklist.new");
  reopenBlocklist();
  return ok;
}

// ---------- OTA blocklist update (browser upload) ----------
static bool upOk = false;
static bool upAuthOk = false;
static File upFile;
static void handleUploadDone() {
  if (!upAuthOk) { web.requestAuthentication(); return; }
  web.send(upOk ? 200 : 500, "text/plain",
           upOk ? "ok" : "rejected: not a BLM1 blocklist.bin");
}
static void handleUpload() {
  HTTPUpload& u = web.upload();
  switch (u.status) {
    case UPLOAD_FILE_START:
      upAuthOk = web.header(CSRF_HEADER) == CSRF_VALUE && web.authenticate(WEB_USER, WEB_PASS);
      if (!upAuthOk) { Serial.println("[ota] blocklist upload: auth/CSRF check failed"); break; }
      upOk = false; beginBlocklistSwap();
      upFile = LittleFS.open("/blocklist.new", "w");
      Serial.printf("[ota] receiving %s\n", u.filename.c_str());
      break;
    case UPLOAD_FILE_WRITE:
      if (upAuthOk && upFile) upFile.write(u.buf, u.currentSize);
      break;
    case UPLOAD_FILE_END:
      if (!upAuthOk) break;
      if (upFile) upFile.close();
      upOk = commitNewBlocklist();
      Serial.printf("[ota] %s -> %u domains\n", upOk ? "OK" : "REJECTED", numHashes);
      break;
    case UPLOAD_FILE_ABORTED:
      if (!upAuthOk) break;
      if (upFile) upFile.close();
      LittleFS.remove("/blocklist.new"); reopenBlocklist();
      Serial.println("[ota] aborted");
      break;
  }
}

// ---------- remote blocklist auto-update ----------
static void loadUpdateCfg() {
  File f = LittleFS.open("/update.cfg", "r");        // runtime config (web /setupdate)
  if (f) {
    updateUrl = f.readStringUntil('\n'); updateUrl.trim();
    String iv = f.readStringUntil('\n'); iv.trim(); if (iv.length()) updateIntervalH = iv.toInt();
    f.close();
  }
  if (!updateUrl.length()) {                         // fall back to the baked /wifi.cfg
    File g = LittleFS.open("/wifi.cfg", "r");
    if (g) {
      while (g.available()) {
        String l = g.readStringUntil('\n'); l.trim();
        int eq = l.indexOf('='); if (eq < 0) continue;
        String k = l.substring(0, eq); k.trim(); k.toUpperCase();
        String v = l.substring(eq + 1); v.trim();
        if (k == "UPDATE_URL") updateUrl = v;
        else if (k == "UPDATE_H" && v.length()) updateIntervalH = v.toInt();
      }
      g.close();
    }
  }
  if (updateIntervalH < 1) updateIntervalH = 1;
}
static void saveUpdateCfg() {
  File f = LittleFS.open("/update.cfg", "w"); if (!f) return;
  f.println(updateUrl); f.println(updateIntervalH); f.close();
}
static bool fetchBlocklist(String url) {
  url.trim(); if (!url.length()) { updateStatus = "no url set"; return false; }
  Serial.printf("[remote] GET %s\n", url.c_str());
#if defined(ESP8266)
  BearSSL::WiFiClientSecure cs; cs.setInsecure();       // blocklist isn't secret -> skip cert pinning
  cs.setBufferSizes(1024, 1024);                        // ESP8266: keep TLS RAM small
  WiFiClient cl;
#else
  WiFiClientSecure cs; cs.setInsecure();
  WiFiClient cl;
#endif
  HTTPClient http; http.setTimeout(20000);
  http.setFollowRedirects(HTTPC_STRICT_FOLLOW_REDIRECTS);  // GitHub release -> CDN redirect
  bool https = url.startsWith("https");
  if (!(https ? http.begin(cs, url) : http.begin(cl, url))) { updateStatus = "begin failed"; return false; }
  int code = http.GET();
  if (code != HTTP_CODE_OK) { http.end(); updateStatus = "HTTP " + String(code); Serial.printf("[remote] %s\n", updateStatus.c_str()); return false; }
  beginBlocklistSwap();
  File f = LittleFS.open("/blocklist.new", "w");
  if (!f) { http.end(); updateStatus = "fs open failed"; reopenBlocklist(); return false; }
  WiFiClient* stream = http.getStreamPtr();
  int len = http.getSize(); uint8_t b[1024]; size_t total = 0; uint32_t idle = millis();
  while (http.connected() && (len < 0 || (int)total < len)) {
    size_t avail = stream->available();
    if (avail) { int n = stream->readBytes(b, avail > sizeof(b) ? sizeof(b) : avail); if (n > 0) { f.write(b, n); total += n; idle = millis(); } }
    else { if (millis() - idle > 15000) break; delay(2); }
  }
  f.close(); http.end();
  bool ok = commitNewBlocklist();
  updateStatus = ok ? ("ok: " + String(numHashes) + " domains") : ("bad data (" + String(total) + "B)");
  Serial.printf("[remote] %s\n", updateStatus.c_str());
  return ok;
}

// ---------- firmware OTA (browser upload of firmware.bin -> reboot) ----------
static bool fwAuthOk = false;
static void handleFwUpdateDone() {
  if (!fwAuthOk) { web.requestAuthentication(); return; }
  bool ok = !Update.hasError();
  web.send(ok ? 200 : 500, "text/plain", ok ? "ok, rebooting" : "firmware update failed");
  if (ok) { delay(300); ESP.restart(); }
}
static void handleFwUpload() {
  HTTPUpload& u = web.upload();
  if (u.status == UPLOAD_FILE_START) {
    fwAuthOk = web.header(CSRF_HEADER) == CSRF_VALUE && web.authenticate(WEB_USER, WEB_PASS);
    if (!fwAuthOk) { Serial.println("[fw-ota] auth/CSRF check failed, rejecting flash"); return; }
    Serial.printf("[fw-ota] %s\n", u.filename.c_str());
#if defined(ESP8266)
    if (!Update.begin((ESP.getFreeSketchSpace() - 0x1000) & 0xFFFFF000)) Update.printError(Serial);
#else
    if (!Update.begin(UPDATE_SIZE_UNKNOWN)) Update.printError(Serial);
#endif
  } else if (u.status == UPLOAD_FILE_WRITE) {
    if (!fwAuthOk) return;
    if (Update.write(u.buf, u.currentSize) != u.currentSize) Update.printError(Serial);
  } else if (u.status == UPLOAD_FILE_END) {
    if (!fwAuthOk) return;
    if (Update.end(true)) Serial.printf("[fw-ota] %u bytes OK\n", u.totalSize);
    else Update.printError(Serial);
  } else if (u.status == UPLOAD_FILE_ABORTED) {
    if (!fwAuthOk) return;
#if defined(ESP8266)
    Serial.println("[fw-ota] aborted");   // ESP8266 Updater has no abort(); next begin() resets it
#else
    Update.abort(); Serial.println("[fw-ota] aborted");
#endif
  }
}

// ---------- WiFi provisioning (SmartConfig / ESP-Touch) ----------
// /wifi.cfg is baked into the LittleFS image by tools/gen_config.py. It takes priority
// over NVS/secrets.h, so re-uploading the filesystem re-provisions without recompiling.
// Format: KEY=VALUE lines (WIFI_SSID, WIFI_PASS, ...).
static bool loadCfgFile(String& ssid, String& pass) {
  File f = LittleFS.open("/wifi.cfg", "r");
  if (!f) return false;
  while (f.available()) {
    String l = f.readStringUntil('\n'); l.trim();
    if (!l.length() || l.startsWith("#")) continue;
    int eq = l.indexOf('='); if (eq < 0) continue;
    String k = l.substring(0, eq); k.trim(); k.toUpperCase();
    String v = l.substring(eq + 1); v.trim();
    if (k == "WIFI_SSID") ssid = v;
    else if (k == "WIFI_PASS") pass = v;
    else if (k == "WIFI_IP") cfgIp = v;
    else if (k == "WIFI_GW") cfgGw = v;
    else if (k == "WIFI_DNS") cfgDns = v;
    else if (k == "WIFI_HOST") cfgHost = v;
  }
  f.close();
  return ssid.length() > 0;
}
static bool hasCreds() {
  String a, b;
  if (loadCfgFile(a, b)) return true;
  prefs.begin("wifi", true); bool nvs = prefs.getString("ssid", "").length() > 0; prefs.end();
  return nvs || (WIFI_SSID && *WIFI_SSID && strcmp(WIFI_SSID, "YOUR_WIFI_SSID") != 0);
}
static bool connectWiFi() {
  String ss, pw;
  const bool fromCfg = loadCfgFile(ss, pw);      // /wifi.cfg (baked) wins
  if (!fromCfg) {
    prefs.begin("wifi", true);
    ss = prefs.getString("ssid", "");
    pw = prefs.getString("pass", "");
    prefs.end();
  }
  const char* ssid = ss.length() ? ss.c_str() : WIFI_SSID;
  const char* pass = ss.length() ? pw.c_str() : WIFI_PASS;
  if (!ssid || !*ssid || strcmp(ssid, "YOUR_WIFI_SSID") == 0) return false;  // unconfigured
  Serial.printf("WiFi: connecting to \"%s\"%s\n", ssid,
                fromCfg ? " (/wifi.cfg)" : (ss.length() ? " (provisioned)" : " (secrets.h)"));
  WiFi.mode(WIFI_STA);
#if defined(ESP8266)
  WiFi.setSleepMode(WIFI_NONE_SLEEP);
  WiFi.setOutputPower(20.5f);                               // max TX power (weak-signal links)
#else
  WiFi.setSleep(false);
  WiFi.setTxPower(WIFI_POWER_19_5dBm);
#endif
  // Hostname (so the router's DHCP list and mDNS show 'esp-adblock').
  const char* host = cfgHost.length() ? cfgHost.c_str() : WIFI_HOST;
  if (host && *host) {
#if defined(ESP8266)
    WiFi.hostname(host);
#else
    WiFi.setHostname(host);
#endif
  }
  // Optional static IP (empty -> DHCP).
  const char* ipc = cfgIp.length() ? cfgIp.c_str() : WIFI_IP;
  const char* gwc = cfgGw.length() ? cfgGw.c_str() : WIFI_GW;
  if (ipc && *ipc) {
    IPAddress ip, gw, sub(255, 255, 255, 0), dns;
    if (ip.fromString(ipc) && gw.fromString(gwc)) {
      const char* dc = cfgDns.length() ? cfgDns.c_str() : WIFI_DNS;
      if (!dc || !*dc || !dns.fromString(dc)) dns = IPAddress(9, 9, 9, 9);
      WiFi.config(ip, gw, sub, dns);
      Serial.printf("WiFi: static IP %s gw %s\n", ipc, gwc);
    }
  }
  WiFi.begin(ssid, pass);
  uint32_t t0 = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - t0 < 30000) { delay(250); Serial.print("."); }
  Serial.println();
  return WiFi.status() == WL_CONNECTED;
}

// ESP-Touch / SmartConfig provisioning: the phone app pushes SSID+password over the
// air, so no SoftAP and no portal are needed. The radio runs in STA+promiscuous only
// during this call, so steady-state cost is zero. Same API on ESP8266 and ESP32.
static bool trySmartConfig(uint32_t timeoutMs) {
  WiFi.mode(WIFI_STA);
#if defined(ESP8266)
  WiFi.setSleepMode(WIFI_NONE_SLEEP);
#else
  WiFi.setSleep(false);
#endif
  WiFi.beginSmartConfig();
  Serial.printf("[smartconfig] waiting %lus for the ESP-Touch app...\n", (unsigned long)(timeoutMs / 1000));
  uint32_t t0 = millis();
  while (!WiFi.smartConfigDone() && millis() - t0 < timeoutMs) { delay(200); Serial.print("."); }
  Serial.println();
  if (!WiFi.smartConfigDone()) { WiFi.stopSmartConfig(); Serial.println("[smartconfig] timeout"); return false; }
  Serial.println("[smartconfig] credentials received, connecting...");
  uint32_t t1 = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - t1 < 20000) { delay(200); Serial.print("."); }
  Serial.println();
  if (WiFi.status() != WL_CONNECTED) { Serial.println("[smartconfig] not connected"); return false; }
  String ss = WiFi.SSID(), pw = WiFi.psk();
  prefs.begin("wifi", false); prefs.putString("ssid", ss); prefs.putString("pass", pw); prefs.end();
  Serial.printf("[smartconfig] saved \"%s\"\n", ss.c_str());
  return true;
}

// Runtime WiFi watchdog: if the link drops, reconnect with a growing backoff capped at 30 s.
static void wifiWatchdog() {
  if (WiFi.status() == WL_CONNECTED) { wifiDownSince = 0; lastReconn = 0; reconnAttempts = 0; return; }
  uint32_t now = millis();
  if (!wifiDownSince) { wifiDownSince = now; lastReconn = now; return; }
  uint32_t backoff = (reconnAttempts > 5) ? 30 : (1u << reconnAttempts);   // 1,2,4,8,16,30(cap)
  if (backoff > 30) backoff = 30;
  if ((uint32_t)(now - lastReconn) >= backoff * 1000UL) {
    lastReconn = now; if (reconnAttempts < 15) reconnAttempts++;
    Serial.printf("[wifi] down %lus — reconnect (backoff %lus)\n",
                  (unsigned long)((now - wifiDownSince) / 1000), (unsigned long)backoff);
    WiFi.reconnect();
  }
}

void setup() {
  Serial.begin(115200); delay(300);
  pinMode(LED_PIN, OUTPUT); digitalWrite(LED_PIN, LED_OFF);
  Serial.println("\n[esp-adblock] booting");
#if defined(ESP8266)
  if (!LittleFS.begin()) { LittleFS.format(); LittleFS.begin(); }
#else
  if (!LittleFS.begin(true)) Serial.println("LittleFS FAILED");
#endif
  reopenBlocklist();
  Serial.printf("blocklist: %u domains\n", numHashes);
  loadRules(); loadHosts(); loadBlockCfg(); loadSyslogCfg(); loadUpdateCfg();
  Serial.printf("rules: block=%d allow=%d keyword=%d\n", numBlock, numAllow, numKw);

  // Hold BOOT at power-on to wipe saved WiFi and force re-provisioning (SmartConfig).
#if defined(ESP8266)
  const int BOOT_PIN = 0;     // ESP8266 BOOT / GPIO0
#elif CONFIG_IDF_TARGET_ESP32C3
  const int BOOT_PIN = 9;     // C3 BOOT button
#else
  const int BOOT_PIN = 0;     // classic ESP32 BOOT button (GPIO9 is a flash pin there)
#endif
  pinMode(BOOT_PIN, INPUT_PULLUP);
  if (digitalRead(BOOT_PIN) == LOW) { delay(60);
    if (digitalRead(BOOT_PIN) == LOW) { prefs.begin("wifi", false); prefs.clear(); prefs.end();
      Serial.println("[setup] BOOT held -> cleared saved WiFi"); } }

  if (!connectWiFi()) {
    if (!hasCreds()) {
      // No credentials: provision via ESP-Touch. Keep listening; retry a fresh window if one lapses.
      while (!trySmartConfig(120000))
        Serial.println("[smartconfig] retry — run the ESP-Touch app on a 2.4 GHz phone");
      Serial.printf("WiFi up (SmartConfig): %s\n", WiFi.localIP().toString().c_str());
    } else {
      // Creds exist but the link is down (router off?): reboot and retry.
      Serial.println("[setup] saved WiFi didn't connect; rebooting in 30s");
      delay(30000); ESP.restart();
    }
  }
  Serial.printf("WiFi up: %s\n", WiFi.localIP().toString().c_str());
  if (MDNS.begin("esp-adblock")) { MDNS.addService("http", "tcp", 80); Serial.println("dashboard: http://esp-adblock.local"); }

  if (strcmp(WEB_PASS, "CHANGE_ME_WEB_PASSWORD") == 0)
    Serial.println("[WARN] secrets.h still has a placeholder WEB_PASS — set a real value "
                    "(config.env) before trusting this device on a network you don't fully control.");

  dnsServer.begin(DNS_PORT); upstreamCli.begin(0);
#if defined(ESP8266)
  web.collectHeaders(CSRF_HEADER);   // ESP8266 variadic overload; a char*[] picks the wrong template
#else
  { const char* hdrs[] = { CSRF_HEADER }; web.collectHeaders(hdrs, 1); }  // needed for requireAuth()'s CSRF check
#endif
  web.on("/", handleRoot);            // dashboard, or block page for a sinkholed host
  web.on("/stats.json", handleStats);
  web.on("/events", handleEvents);          // recent-blocked ring (frontend keeps history)
  web.on("/allow", handleAllow);             // block-page "continue" (CSRF-gated, no Basic auth)
  web.on("/setblock", handleSetBlock);       // blocked-reply mode (ip/zero/nxdomain)
  web.on("/setsyslog", handleSetSyslog);     // remote syslog host/port
  web.on("/sethost", handleSetHost);         // local DNS record add/replace
  web.on("/delhost", handleDelHost);         // local DNS record remove
  web.on("/addblock", []() { if (!requireAuth()) return; addBlock(web.arg("d")); web.send(200, "text/plain", "ok"); });
  web.on("/unblock", []() { if (!requireAuth()) return; removeBlock(web.arg("d")); web.send(200, "text/plain", "ok"); });
  web.on("/pause", []() {                    // /pause?s=300  (0 or absent = indefinite)
    if (!requireAuth()) return;
    long s = web.hasArg("s") ? web.arg("s").toInt() : 0;
    blockingOn = false; resumeAt = (s > 0) ? millis() + (uint32_t)s * 1000UL : 0;
    web.send(200, "text/plain", "paused");
  });
  web.on("/resume", []() { if (!requireAuth()) return; blockingOn = true; resumeAt = 0; web.send(200, "text/plain", "resumed"); });
  web.on("/forgetwifi", []() { if (!requireAuth()) return; web.send(200, "text/plain", "cleared — rebooting; provide WiFi via SmartConfig");
    prefs.begin("wifi", false); prefs.clear(); prefs.end(); delay(500); ESP.restart(); });
  web.on("/upload", HTTP_POST, handleUploadDone, handleUpload);      // blocklist OTA (auth inside handleUpload)
  web.on("/update", HTTP_POST, handleFwUpdateDone, handleFwUpload);  // firmware OTA (auth inside handleFwUpload)
  web.on("/fetchnow", []() { if (!requireAuth()) return; fetchBlocklist(updateUrl); web.send(200, "text/plain", updateStatus); });
  web.on("/setupdate", []() {
    if (!requireAuth()) return;
    if (web.hasArg("u")) updateUrl = web.arg("u");
    if (web.hasArg("h")) { updateIntervalH = web.arg("h").toInt(); if (updateIntervalH < 1) updateIntervalH = 1; }
    saveUpdateCfg(); web.send(200, "text/plain", "ok");
  });
  web.onNotFound(handleNotFound);            // sinkholed hosts -> block page
  web.begin();
  ArduinoOTA.setHostname("esp-adblock");   // pio run -t upload --upload-port esp-adblock.local
  ArduinoOTA.setPassword(WEB_PASS);   // OTA uses the dashboard credential — no separate OTA password
  ArduinoOTA.begin();
  Serial.println("DNS :53 + dashboard :80 + OTA up");
}

void loop() {
  uint32_t _l = micros();
  static uint32_t _prev = 0; if (_prev && _l - _prev > stMaxGap) stMaxGap = _l - _prev; _prev = _l;
  ArduinoOTA.handle();
  wifiWatchdog();
  uint32_t _d0 = micros();
  bool busy = handleDns();               // DNS first (latency-sensitive)
  uint32_t _dd = micros() - _d0; if (_dd > stMaxDns) stMaxDns = _dd;
  pollUpstream();                        // relay any upstream replies for in-flight queries
  if (!busy || (uint32_t)(millis() - lastWeb) > 100) {   // web only when idle (anti-starvation cap)
    lastWeb = millis();
    uint32_t _w0 = micros(); web.handleClient(); uint32_t _ww = micros() - _w0; if (_ww > stMaxWeb) stMaxWeb = _ww;
  }
#if defined(ESP8266)
  MDNS.update();
#endif
  if (!blockingOn && resumeAt && (int32_t)(millis() - resumeAt) >= 0) { blockingOn = true; resumeAt = 0; }
  if (updateUrl.length()) {               // periodic remote blocklist auto-update
    uint32_t now = millis();
    if (lastCheckMs == 0) lastCheckMs = now;   // skip an immediate fetch on boot
    else if (now - lastCheckMs >= updateIntervalH * 3600000UL) { lastCheckMs = now; fetchBlocklist(updateUrl); }
  }
  flushSyslogLazy(!busy);   // lazy: only when idle and nothing in flight (no DNS latency impact)
  if (ledUntil && (int32_t)(millis() - ledUntil) >= 0) { digitalWrite(LED_PIN, LED_OFF); ledUntil = 0; }   // status LED off
  if (!busy) delay(1);   // sleep only when idle: full speed under load, cool when quiet
}
